# 2026-11-10 (Claude): regenerates section 2 (SCRIPTS) of C:\Users\Amaury\Desktop\claude_files_outside_git.txt: every
# folder already listed there + the folders given as arguments are rescanned (.py / .sh, first comment lines as the
# description, "[OBSOLETE]" when the folder has an OBSOLETE_README.txt naming the file). Section 1 is kept as it is.
# usage: python update_claude_lists.py [new folder ...]
import os, re, sys, datetime
F = '/mnt/c/Users/Amaury/Desktop/claude_files_outside_git.txt'
txt = open(F).read()
head, sec2 = txt.split('\n2. SCRIPTS', 1)
head = head.rstrip('=\n') + '\n'
dirs = re.findall(r'^(/\S+/)$', sec2, flags=re.M)
for d in sys.argv[1:]:
    d = d.rstrip('/') + '/'
    if d not in dirs: dirs.append(d)
def describe(p):
    lines = []
    try:
        for l in open(p, errors='replace'):
            l = l.strip()
            if l.startswith('#!'): continue
            if l.startswith('#'):
                lines.append(l.lstrip('#').strip())
                if len(' '.join(lines)) > 200: break
            elif lines or l: break
    except OSError: return ''
    return ' '.join(lines)[:200]
out = []
for d in sorted(dirs, key=str.lower):
    if not os.path.isdir(d): continue
    files = sorted(f for f in os.listdir(d) if f.endswith(('.py', '.sh')))
    if not files: continue
    obs = open(d + 'OBSOLETE_README.txt').read() if os.path.exists(d + 'OBSOLETE_README.txt') else ''
    out.append(f'\n{d}')
    for f in files:
        tag = '[OBSOLETE] ' if re.search(r'^OBSOLETE FILES:.*\b' + re.escape(f) + r'\b', obs, flags=re.M) else ''
        out.append(f'  {f:38s} {tag}{describe(d + f)}')
today = datetime.date.today().isoformat()
head = re.sub(r'\(list of [0-9-]+\)', f'(list of {today})', head, count=1)
open(F, 'w').write(head + '=' * 117 + '\n2. SCRIPTS (first comment line of each file; empty = small run script without header, or a generated copy of\n'
                   '   SGD_jax_CNN.py with its main loop replaced, e.g. SGD_jax_CNN_show.py). Regenerated by\n'
                   '   tools/update_claude_lists.py of the 4polarMFM_these repo\n' + '=' * 117 + '\n' + '\n'.join(out) + '\n')
print(f'{len(dirs)} folders, written {F}')
